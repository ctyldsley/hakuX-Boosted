# hakuX-Boosted: lfs and stfs move a NaN without making it quiet (the
# host's conversion would). On ARM64 they are one conversion with the NaN
# case out of line (CONVERT_KEEP_NAN, a64_sequences.cc); these are the cases
# that take that path and the ones beside it.

test_lfs_nan_snan:
  #_ MEMORY_IN 10001000 7F A0 00 01 00 00 00 00
  #_ REGISTER_IN r4 0x0000000010001000
  lfs f3, 0(r4)
  blr
  #_ REGISTER_OUT r4 0x0000000010001000
  #_ REGISTER_OUT f3 0x7FF4000020000000

